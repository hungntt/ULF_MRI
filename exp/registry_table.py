"""Which enhancer models each analysis used.

Every set is read from the analysis's own output, not typed by hand. Output:
out_public/coauthor_enhancer_sets.md

    python exp/registry_table.py
"""
import json
import os
import re

import numpy as np

ROOT = "."
OUT = os.environ.get("ULF_OUT", f"{ROOT}/out_public")

FAMILY = {
    "U-Net L1": "supervised U-Net", "U-Net L1+SSIM": "supervised U-Net", "U-Net absolute": "supervised U-Net",
    "U-Net L1, long schedule": "supervised U-Net", "cGAN / pix2pix": "adversarial", "LoHiResGAN": "adversarial",
    "corpus-calibrated": "corpus-pretrained", "corpus, uncalibrated": "corpus-pretrained",
    "corpus, physics operator": "corpus-pretrained", "Gaussian-NLL head": "probabilistic head",
    "quantile (CQR) head": "probabilistic head", "wavelet diffusion": "diffusion",
}
ALIAS = {"D1 calibrated corpus": "corpus-calibrated"}
SEEDED = re.compile(r"^(.*) s(\d)$")

ANALYSES = {
    "zoo": dict(label="Zoo, selection and metric correlation", src="d3zoo_T2.json",
                paper="Sec. 4 selection, Fig. 4, Table sites; rho over 12 configurations, seeds averaged"),
    "stage": dict(label="Stage-wise retention, seed-averaged analyses", src="d3stage_rows_test_T2.meta.json",
                  paper="App. operator; App. I"),
    "offlesion": dict(label="Off-lesion structure", src="d3offlesion_T2.json",
                      paper="App. off-lesion (per configuration over its seeds)"),
    "robust": dict(label="Robustness of measurement choices", src="d3robust_rows_std_test_T2.npz",
                   paper="App. robustness"),
    "h2lo": dict(label="Third-party operator H2LO", src="d3h2lo_T2.json", paper="App. operator, Table operator"),
    "kscale_seed0": dict(label="Erasure under k-scaled D (review B)", src="d1_physcheck_erasure.json",
                         paper="Sec. 4.1 conservative-erasure statement"),
    "location": dict(label="Location and enhancer (200 sites)", src="d3xarch_rows_T2.json", paper="Fig. 2a"),
    "map_xarch": dict(label="Retention map on unseen enhancers", src="d3xarch_T2.json",
                      paper="Table general (training model plus five unseen)"),
    "real_ms": dict(label="Real MS lesions", src="d3reallesion.json", paper="Sec. 4 real lesions, App. lesions"),
}


def J(name):
    return json.load(open(f"{OUT}/{name}"))


def _split(name):
    name = ALIAS.get(name, name)
    m = SEEDED.match(name)
    return (m.group(1), int(m.group(2))) if m else (name, 0)


def model_sets():
    """analysis -> sorted list of (configuration, seed)."""
    s = {}
    s["zoo"] = sorted({(v["enhancer"], int(v["seed"])) for v in J("d3zoo_T2.json").values()})
    meta = J("d3stage_rows_test_T2.meta.json")["models"]
    s["stage"] = sorted({(c, int(sd)) for c, sd, _ in meta.values() if c != "no enhancer"})
    pe = J("d3offlesion_T2.json")["splits"]["test"]["per_enhancer"]["HFC"]
    zoo_seeds = {}
    for c, sd in s["zoo"]:
        zoo_seeds.setdefault(c, []).append(sd)
    s["offlesion"] = sorted({(c, sd) for c in pe if c != "no enhancer" for sd in zoo_seeds[c]})
    z = np.load(f"{OUT}/d3robust_rows_std_test_T2.npz", allow_pickle=True)
    s["robust"] = sorted({(str(c), int(sd)) for c, sd in zip(z["enhancer"], z["seed"]) if str(c) in FAMILY})
    s["h2lo"] = sorted({(c, 0) for c in J("d3h2lo_T2.json")["per"]["HFC"]})
    enh = J("d1_physcheck_erasure.json")["splits"]["test"]["HFC"]["enhancers"]
    s["kscale_seed0"] = sorted({(c, 0) for c in enh if not c.startswith("no enhancer")})
    s["location"] = sorted({_split(r["arch"]) for r in J("d3xarch_rows_T2.json")})
    s["map_xarch"] = sorted({_split(k) for k in J("d3xarch_T2.json")})
    tr = J("d3reallesion.json")["transplant"]
    s["real_ms"] = sorted({_split(k) for k in tr if k not in ("no enhancer", "R_D")})
    return s


def markdown(sets):
    confs = list(FAMILY)
    L = ["# Enhancer models used by each analysis", "",
         "Generated by `exp/registry_table.py` from each analysis's own output in `out_public/`. "
         "A cell gives the seeds used (0 = first seed). Five-seed configurations were trained with seeds 0-4; "
         "the others once.", "",
         "| configuration | family | trained seeds | " + " | ".join(a for a in sets) + " |",
         "|---|---|---|" + "---|" * len(sets)]
    zoo = {}
    for c, sd in sets["zoo"]:
        zoo.setdefault(c, []).append(sd)
    for c in confs:
        cells = []
        for a in sets:
            sd = sorted(x for cc, x in sets[a] if cc == c)
            cells.append("-" if not sd else ("0-4" if sd == [0, 1, 2, 3, 4] else ",".join(map(str, sd))))
        L.append(f"| {c} | {FAMILY[c]} | {len(zoo.get(c, []))} | " + " | ".join(cells) + " |")
    L.append("| **models / configurations** | | | " + " | ".join(
        f"{len(sets[a])} / {len({c for c, _ in sets[a]})}" for a in sets) + " |")
    L += ["", "## Analyses", "", "| column | analysis | source | used in |", "|---|---|---|---|"]
    for a in sets:
        L.append(f"| {a} | {ANALYSES[a]['label']} | `out_public/{ANALYSES[a]['src']}` | {ANALYSES[a]['paper']} |")
    L += ["", "Inclusion rules: the 12 configurations map 64mT T2 to 3T T2 with three adjacent slices as input and were "
          "trained on the 15 OpenNeuro training subjects. Models trained on three subjects or on deliberately "
          "mismatched pairs are negative controls and are excluded from every column. H2LO and the k-scaled "
          "erasure of review B skip wavelet diffusion (`exp/d3h2lo.py:213` filters `diff`, as `d3dfactor` does). "
          "The location analysis and the map's cross-enhancer test use the first seed of the six five-seed "
          "configurations. Real MS lesions use the first seed of all 12 configurations. "
          "Released models (SuperSynth, SynthSR, GAMBAS) and the cross-contrast routes A-C are separate sets "
          "and are not enhancer configurations."]
    return "\n".join(L) + "\n"


def main():
    s = model_sets()
    open(f"{OUT}/coauthor_enhancer_sets.md", "w").write(markdown(s))
    for a, v in s.items():
        print(f"  {a:14s} {len(v):3d} models, {len({c for c, _ in v}):2d} configurations")


if __name__ == "__main__":
    main()
