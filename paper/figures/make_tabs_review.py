# ------------------------------------------------------------------ released
def sym_table(sfx):
    rows = J(f"d3pretrained_rows{sfx}.json")["rows"] + J(f"d3pretrained_zoo_rows{sfx}.json")["rows"]
    agg = {}
    for r in rows:
        if r.get("bench", "T2") != "T2" or r.get("mode", "slab") != "slab" or r["arm"] != "sim":
            continue
        m = r["model"] if r["family"] != "zoo" else r.get("enhancer", r["model"])
        v = r["tp"] * np.sqrt(r["a"] / r["k"]) / r["ty"] if r["a"] > 0 and r["k"] > 0 else np.nan
        agg.setdefault(m, []).append(v)
    return {m: (float(np.nanmean(v)), float(np.nanmean(np.array(v) < 0.25))) for m, v in agg.items()}


