def offlesion():
    """Off-lesion structure caused by an inserted lesion (exp/d3offlesion.py), synthetic arm."""
    r = J("d3offlesion_T2.json")["splits"]
    cohorts = [("test", "OpenNeuro"), ("ext_v5", "Zenodo"), ("pub3t_unc", "UNC"), ("pub3t_penn", "Penn"),
               ("pub3t_hip", "Hippocampal")]
    t = r["test"]["per_enhancer"]["HFC"]
    gap = lambda ks: max(abs(r[k]["per_enhancer"]["HFE"][e]["rate"]["mean"] - r[k]["per_enhancer"]["HFC"][e]["rate"]["mean"])
                         for k in ks for e in t)
    g_other, g_hip = gap([k for k, _ in cohorts[:-1]]), gap(["pub3t_hip"])
    order = ["no enhancer"] + sorted([e for e in t if e != "no enhancer"], key=lambda e: -t[e]["R"]["mean"])
    s = ["% Generated by figures/make_tabs_review.py from out_public/d3offlesion_T2.json.",
         "\\begin{table}[!htbp]", "\\floatconts{tab:offlesion}",
         "{\\caption{\\textbf{Off-lesion structure caused by an inserted lesion.} Percentage of lesions after "
         "whose insertion the output showed, at least two footprint radii away, a structure of the same size and sign "
         "with at least 25\\% (or 50\\%) of the inserted contrast, through $D$ (unit 1), seeds averaged. Rows are "
         "ordered by retention on OpenNeuro. The OpenNeuro 3T images are shared by both 64mT units, so the "
         "synthetic arm has one OpenNeuro column. Under unit 2 the rates differed by at most "
         f"{100 * g_other:.0f} percentage points ({100 * g_hip:.0f} in Hippocampal).}}}}",
         "{\\scriptsize\\setlength{\\tabcolsep}{3pt}\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lcccccc@{}}", "\\toprule",
         "& \\multicolumn{2}{c}{OpenNeuro} & Zenodo & UNC & Penn & Hippocampal \\\\",
         "\\cmidrule(lr){2-3}",
         "Enhancer & $\\geq 25\\%$ & $\\geq 50\\%$ & $\\geq 25\\%$ & $\\geq 25\\%$ & $\\geq 25\\%$ & $\\geq 25\\%$ \\\\",
         "\\midrule"]
    for e in order:
        cells = [f"{100 * t[e]['rate']['mean']:.1f}", f"{100 * t[e]['rate_05']['mean']:.1f}"]
        cells += [f"{100 * r[k]['per_enhancer']['HFC'][e]['rate']['mean']:.1f}" for k, _ in cohorts[1:]]
        s.append(f"{NAME.get(e, e)} & " + " & ".join(cells) + " \\\\")
        if e == "no enhancer":
            s.append("\\midrule")
    s += ["\\bottomrule", "\\end{tabular*}}", "\\end{table}", ""]
    write("tab_offlesion_rev.tex", "\n".join(s))
    keys = [k for k, _ in cohorts]
    rng = lambda e, f="rate": [min(r[k]["per_enhancer"][o][e][f]["mean"] for k in keys for o in ("HFC", "HFE")),
                               max(r[k]["per_enhancer"][o][e][f]["mean"] for k in keys for o in ("HFC", "HFE"))]
    NUM["offlesion"] = dict(unit_gap=[g_other, g_hip],
        rate_range={e: rng(e) for e in order},
        rate05_max_excl_cqr_excl_hip=max(r[k]["per_enhancer"][o][e]["rate_05"]["mean"] for k in keys[:-1]
                                         for o in ("HFC", "HFE") for e in order if e != "quantile (CQR) head"),
        rate05_max_excl_cqr_hip=max(r["pub3t_hip"]["per_enhancer"][o][e]["rate_05"]["mean"] for o in ("HFC", "HFE")
                                    for e in order if e != "quantile (CQR) head"),
        rate05_range_cqr=rng("quantile (CQR) head", "rate_05"),
        rho_rate_vs_R=[min(r[k]["rho_rate_vs_R"][o]["all"] for k in keys for o in ("HFC", "HFE")),
                       max(r[k]["rho_rate_vs_R"][o]["all"] for k in keys for o in ("HFC", "HFE"))])



