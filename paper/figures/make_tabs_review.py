    s += ["\\begin{minipage}[t]{0.5\\linewidth}", "\\begin{tabular*}{\\linewidth}[t]{@{\\extracolsep{\\fill}}lcc@{}}", "\\toprule", "Model & Same sign & Opposite sign \\\\", "\\midrule"]
    for m, lab in (("A_T1in", "Route A (T1 in)"), ("B_T2in", "Route B (T2 in)"), ("C_both", "Route C (T1 + T2 in)"),
                   ("SynthSR low-field (T2 in)", "SynthSR low-field, T2 in"),
                   ("SuperSynth T1 (T2 in)", "SuperSynth, T2 in"), ("SynthSR Hyperfine (T1+T2 in)", "SynthSR Hyperfine, T1 + T2"),
                   ("SuperSynth T1 (T1 in)", "SuperSynth, T1 in")):
        s.append(f"{lab} & {inv(m, 't1b_t2b'):.0f}\\% & {inv(m, 't1d_t2b'):.0f}\\% \\\\")
        NUM[f"inv|{m}"] = [inv(m, "t1b_t2b"), inv(m, "t1d_t2b")]
