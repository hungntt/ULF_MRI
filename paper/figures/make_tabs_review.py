"""Appendix tables of the paper (validation analyses), written from out_public/, and the
numbers the new text quotes (review_numbers.json), so every new value can be traced to a result file.

    python -I -B paper/figures/make_tabs_review.py

Writes, next to this script:
    tab_operator_rev.tex   physical check of D and the independent operator H2LO
    tab_lesions_rev.tex    real MS lesions (transplant) and real stroke lesions (ATLAS)
    tab_robust_rev.tex     erasure threshold, lesion profile and region definition, negative controls
    tab_offlesion_rev.tex  off-lesion structure caused by an inserted lesion (specificity)
    tab_released_rev.tex   released models: T2 benchmark and T1 wrong-sign rates
    review_numbers.json
Sources: d1_physcheck.json, d1_physcheck_erasure.json, d3h2lo_T2.json, d3reallesion.json,
d3atlas_T1.json, d3robust_T2.json, d3offlesion_T2.json, d3pretrained{,_ext_v5}.json and their row files.
"""
import json, os
import numpy as np

OUT = os.environ.get("ULF_OUT", "./out_public")
HERE = os.path.dirname(os.path.abspath(__file__))
NAME = {"U-Net L1": "U-Net $L_1$", "U-Net L1+SSIM": "U-Net $L_1$+SSIM", "U-Net absolute": "U-Net, absolute output",
        "cGAN / pix2pix": "pix2pix", "LoHiResGAN": "LoHiResGAN", "corpus-calibrated": "Corpus, calibrated",
        "U-Net L1, long schedule": "U-Net $L_1$, long schedule", "corpus, uncalibrated": "Corpus, uncalibrated",
        "corpus, physics operator": "Corpus, physics operator", "Gaussian-NLL head": "Gaussian head",
        "quantile (CQR) head": "Quantile (CQR) head", "wavelet diffusion": "Wavelet diffusion",
        "no enhancer": "No enhancer (64mT input)"}
NUM = {}
J = lambda f: json.load(open(f"{OUT}/{f}"))
ci = lambda c, d=2: f"[{c[0]:.{d}f}, {c[1]:.{d}f}]"


def strip_seed(n):
    return n[:-3] if n.endswith((" s0", " s1", " s2", " s3", " s4")) else n


def write(name, s):
    open(f"{HERE}/{name}", "w").write(s)


# ------------------------------------------------------------------ operator
def operator():
    a = J("d1_physcheck.json")["analyses"]
    units = [("HFC", "D_HFC", "OpenNeuro, unit 1"), ("HFE", "D_HFE", "OpenNeuro, unit 2"), ("V5", "D_HFC", "Zenodo")]
    rows = [("ventricle", None, "Lateral-ventricle edge (control)"),
            ("sulcal_csf", "1-2", "Sulcal CSF, 1--2\\,mm"), ("sulcal_csf", "2-3", "Sulcal CSF, 2--3\\,mm (4\\,mm lesion)"),
            ("sulcal_csf", "3-5", "Sulcal CSF, 3--5\\,mm (6, 8\\,mm)"), ("sulcal_csf", "5-8", "Sulcal CSF, 5--8\\,mm (12\\,mm)"),
            ("pvs", "1-2", "Perivascular spaces, 1--2\\,mm")]
    key = lambda u, op, c, b: f"T2|{u}|{op}|ventricle|reg|c0.05" if c == "ventricle" else f"T2|{u}|{op}|{c}|3d|{b}|reg|c0.05"
    s = ["% Generated by figures/make_tabs_review.py from out_public/d1_physcheck.json and d3h2lo_T2.json.",
         "\\begin{table}[!htbp]", "\\floatconts{tab:operator}",
         "{\\caption{\\textbf{Validity of the degradation operator.} Top: contrast transfer of real anatomy, "
         "$k = C(x)/C(D(y))$, median over structure instances with 95\\% subject-cluster bootstrap intervals; "
         "$k>1$ means that $D$ attenuates the structure more than the scanner. Thickness bins are matched to "
         "lesion sizes by the full width at half maximum of the Gaussian profile. Bottom: retention through "
         "degradation alone ($R_D$) and mean retention of 11 enhancers under our two operators and the "
         "independently developed H2LO, for the same 384 lesions of the internal test set, and the Spearman "
         "correlation of the enhancer ranking with $D$ (unit 1). The released H2LO weights were trained on 3 of "
         "the 5 test subjects, so the last two columns repeat $R_D$ and $\\rho$ in the other 2.}}",
         "{\\scriptsize\\setlength{\\tabcolsep}{3pt}\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lccc@{}}", "\\toprule",
         "Structure & " + " & ".join(u[2] for u in units) + " \\\\", "\\midrule"]
    for c, b, lab in rows:
        cells = []
        for u, op, _ in units:
            v = a.get(key(u, op, c, b))
            cells.append(f"{v['k_median']:.2f} {ci(v['k_median_ci'])}" if v else "--")
            NUM[f"k|{u}|{c}|{b}"] = v["k_median"] if v else None
        s.append(f"{lab} & " + " & ".join(cells) + " \\\\")
    s += ["\\bottomrule", "\\end{tabular*}", "\\par\\vspace{2ex}"]
    h = J("d3h2lo_T2.json")
    lab = {"HFC": "$D$, unit 1", "HFE": "$D$, unit 2", "H2LO sphere": "H2LO, spherical lesion",
           "H2LO": "H2LO, 1\\,mm-thick lesion"}
    from scipy.stats import spearmanr
    g2 = h["per_group"]["not_in_h2lo_train"]
    names = list(g2["HFC"])
    s += ["\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lccccc@{}}", "\\toprule",
          "& \\multicolumn{3}{c}{5 subjects} & \\multicolumn{2}{c}{2 subjects} \\\\",
          "\\cmidrule(lr){2-4}\\cmidrule(l){5-6}",
          "Operator & $R_D$ & Mean $R$ & $\\rho$ & $R_D$ & $\\rho$ \\\\", "\\midrule"]
    for o in ("HFC", "HFE", "H2LO sphere", "H2LO"):
        rr = np.mean([v["R"] for v in h["per"][o].values()])
        rho = "--" if o == "HFC" else f"{h['rank_rho'][('HFC vs ' + o)]['rho']:.2f}"
        r2 = None if o == "HFC" else float(spearmanr([g2["HFC"][n]["R"] for n in names],
                                                     [g2[o][n]["R"] for n in names]).statistic)
        rd2 = h["R_D_by_group"]["not_in_h2lo_train"][o]
        s.append(f"{lab[o]} & {h['R_D'][o]:.3f} & {rr:.3f} & {rho} & {rd2:.3f} & {'--' if r2 is None else f'{r2:.2f}'} \\\\")
        NUM[f"h2lo|{o}|R_D"] = h["R_D"][o]
        NUM[f"h2lo2|{o}|R_D"] = rd2
        NUM[f"h2lo2|{o}|rho"] = r2
    s += ["\\bottomrule", "\\end{tabular*}}", "\\end{table}", ""]
    write("tab_operator_rev.tex", "\n".join(s))
    e = J("d1_physcheck_erasure.json")["splits"]["test"]["HFC"]["enhancers"]
    NUM["kscaled_pix2pix"] = [e["cGAN / pix2pix"]["erased_k1"], e["cGAN / pix2pix"]["fwhm"]["erased"]]


# ------------------------------------------------------------------ real lesions
def lesions():
    m = J("d3reallesion.json")
    t = {k: v for k, v in m["transplant"].items() if isinstance(v, dict) and "R_real" in v}
    order = sorted(t, key=lambda k: -t[k]["R_real"])
    s = ["% Generated by figures/make_tabs_review.py from out_public/d3reallesion.json and d3atlas_T1.json.",
         "\\begin{table}[!htbp]", "\\floatconts{tab:lesions}",
         "{\\caption{\\textbf{Real lesions against matched Gaussians.} Top: 534 real MS lesions transplanted into "
         "healthy 3T targets (seed-0 enhancers, $D$ unit 1), each paired with a Gaussian of the same centre, "
         "equivalent radius and core contrast. Er.: lesions erased ($R<0.25$). Bottom: 684 real stroke lesions "
         "(ATLAS) on T1, by equivalent diameter. 2D: central slice through $D$ (no enhancer and route A). 3D: "
         "released models on the OpenNeuro targets, outputs mapped to 3T units by the ratio of standard "
         "deviations. Intervals: 95\\% bootstrap over source subjects.}}",
         "{\\scriptsize\\setlength{\\tabcolsep}{2.5pt}\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lcccc@{}}", "\\toprule",
         "MS lesions & $R$ real & $R$ Gaussian & Er. real & Er. Gauss. \\\\", "\\midrule"]
    for k in order:
        v = t[k]
        s.append(f"{NAME.get(strip_seed(k), strip_seed(k))} & {v['R_real']:.3f} & {v['R_gauss']:.3f} & "
                 f"{100 * v['erased_real']:.0f}\\% & {100 * v['erased_gauss']:.0f}\\% \\\\")
    s += ["\\midrule", f"Ranking, real vs Gaussian & \\multicolumn{{4}}{{l}}{{$\\rho = {m['ranking']['real_vs_gauss']['rho']:.2f}$ "
          f"{ci(m['ranking']['real_vs_gauss']['ci'])}}} \\\\", "\\bottomrule", "\\end{tabular*}", "\\par\\vspace{2ex}"]
    NUM["ms_rank_rho"] = m["ranking"]["real_vs_gauss"]
    NUM["ms_map_auroc"] = dict(real=m["map"]["real"]["d3detect_T2"], gauss=m["map"]["gauss"]["d3detect_T2"])
    a = J("d3atlas_T1.json")
    st = ["4-12 mm", "12-25 mm", ">25 mm"]
    s += ["\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lccc@{}}", "\\toprule",
          "Stroke lesions & 4--12\\,mm & 12--25\\,mm & $>$25\\,mm \\\\", "\\midrule"]
    for nm, lab in (("no enhancer", "2D, no enhancer"), ("route A (T1 U-Net)", "2D, route A")):
        o = a["two_d"][nm]
        s.append(f"{lab}, $R$ real & " + " & ".join(f"{o[x]['R_real']:.2f}" for x in st) + " \\\\")
        s.append(f"{lab}, $R$ Gaussian & " + " & ".join(f"{o[x]['R_gauss']:.2f}" for x in st) + " \\\\")
        s.append(f"{lab}, Er. real & " + " & ".join(f"{100 * o[x]['erased_real']:.0f}\\%" for x in st) + " \\\\")
    s.append("\\midrule")
    for nm, lab in (("64 mT input (no enhancer, 3D)", "3D, no enhancer"), ("SuperSynth T1 (T1 in)", "3D, SuperSynth"),
                    ("SynthSR low-field (T1 in)", "3D, SynthSR")):
        o = a["three_d"][nm]
        s.append(f"{lab}, $R$ & " + " & ".join(f"{o[x]['symmetric']['R']:.2f}" for x in st) + " \\\\")
        s.append(f"{lab}, Er. & " + " & ".join(f"{100 * o[x]['symmetric']['erased']:.0f}\\%" for x in st) + " \\\\")
