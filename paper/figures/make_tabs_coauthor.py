"""Appendix I tables of the paper (seed averaging, selection checks, map baseline), written from out_public/, and the numbers the new text quotes (coauthor_numbers.json).

    python -I -B paper/figures/make_tabs_coauthor.py

Writes, next to this script:
    tab_seeds_rev.tex      erasure per configuration: both seed estimands, k-scaled D, acquired-input arm
    tab_selection_rev.tex  SynthSeg pick against the retention leader: as published, cross-fitted, without the
                           corpus family, under k-scaled D
    tab_mapbase_rev.tex    retention map against handcrafted baselines
    coauthor_numbers.json
Sources: coauthor_stats_T2.json, coauthor_kscale_T2.json, coauthor_baseline_T2.json, coauthor_inpaint_T2.json,
coauthor_darkbright_T2.json, coauthor_denominator_T2.json.
"""
import json
import os

import numpy as np

OUT = os.environ.get("ULF_OUT", "./out_public")
HERE = os.path.dirname(os.path.abspath(__file__))
J = lambda f: json.load(open(f"{OUT}/{f}"))
NAME = {"U-Net L1": "U-Net $L_1$", "U-Net L1+SSIM": "U-Net $L_1$+SSIM", "U-Net absolute": "U-Net, absolute output",
        "cGAN / pix2pix": "pix2pix", "LoHiResGAN": "LoHiResGAN", "corpus-calibrated": "Corpus, calibrated",
        "U-Net L1, long schedule": "U-Net $L_1$, long schedule", "corpus, uncalibrated": "Corpus, uncalibrated",
        "corpus, physics operator": "Corpus, physics operator", "Gaussian-NLL head": "Gaussian head",
        "quantile (CQR) head": "Quantile (CQR) head", "wavelet diffusion": "Wavelet diffusion",
        "no enhancer": "No enhancer (64mT input)"}
COHORT = {"test": "OpenNeuro unit 1", "ext_on_hfe": "OpenNeuro unit 2", "ext_v5": "Zenodo"}
NUM = {}
pc = lambda v: f"{100 * v:.0f}"
pp = lambda v: f"{100 * v:.1f}"


def write(name, s):
    open(f"{HERE}/{name}", "w").write(s)


def tab_seeds():
    st = J("coauthor_stats_T2.json")["task6"]["test"]["HFC"]
    ks = J("coauthor_kscale_T2.json")["test"]["HFC"]
    s, a = st["syn"], st["acq"]
    order = ["no enhancer"] + sorted((c for c in s if c != "no enhancer"), key=lambda c: s[c]["rank"])
    L = ["% Generated by figures/make_tabs_coauthor.py from out_public/coauthor_stats_T2.json and coauthor_kscale_T2.json.",
         r"\begin{table}[!htbp]", r"\floatconts{tab:seeds}",
         r"{\caption{\textbf{Erasure per configuration on the internal test set, through $D$ (unit 1).} The same 480 "
         r"lesions (5 subjects) pass through every model. Mean $\mathcal{R}$ averages seeds per lesion, and seed s.d. is the "
         r"standard deviation of a model's mean $\mathcal{R}$ over its five seeds. Erased (\%, $\mathcal{R}<0.25$): "
         r"per-seed is the mean of the models' erased fractions, seed-mean the erased fraction of the seed-averaged "
         r"retention. $k$-scaled: $D$'s lesion response multiplied by the $k$ of the lesion's size bin "
         r"(\appendixref{app:operator}). Acquired: the acquired-input arm, per-seed.}}",
         r"{\scriptsize\setlength{\tabcolsep}{3pt}\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lccccccc@{}}",
         r"\toprule",
         r"& & & & \multicolumn{3}{c}{Erased, synthetic} & Erased, acquired \\ \cmidrule(lr){5-7}",
         r"Configuration & Seeds & Mean $\mathcal{R}$ & Seed s.d. & Per-seed & Seed-mean & $k$-scaled & $k{=}1$ / $k$-scaled \\",
         r"\midrule"]
    for c in order:
        v = s[c]
        sd = "--" if v["seed_sd"] is None else f"{v['seed_sd']:.3f}"
        L.append(f"{NAME[c]} & {v['n_seeds'] if c != 'no enhancer' else '--'} & {v['mean_R']:.3f} & {sd} & "
                 f"{pc(v['erased_perseed']['0.25'])} & {pc(v['erased_seedmean']['0.25'])} & "
                 f"{pc(ks['syn']['per_config'][c]['erased_k'])} & {pc(a[c]['erased_perseed']['0.25'])} / "
                 f"{pc(ks['acq']['per_config'][c]['erased_k'])} \\\\")
        if c == "no enhancer":
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular*}}", r"\end{table}"]
    write("tab_seeds_rev.tex", "\n".join(L) + "\n")
    five = [c for c in s if s[c]["n_seeds"] == 5]
    NUM["seeds"] = dict(max_estimand_gap_pp=max(100 * abs(s[c]["erased_perseed"]["0.25"] - s[c]["erased_seedmean"]["0.25"]) for c in five),
                        seed_sd_unet=[min(s[c]["seed_sd"] for c in five if c not in ("cGAN / pix2pix", "LoHiResGAN")),
                                      max(s[c]["seed_sd"] for c in five if c not in ("cGAN / pix2pix", "LoHiResGAN"))],
                        seed_sd_gan=[s["cGAN / pix2pix"]["seed_sd"], s["LoHiResGAN"]["seed_sd"]],
                        lohires_per_seed_R=s["LoHiResGAN"]["per_seed_mean_R"])
    drops = {c: p["drop_perseed"] for c, p in ks["syn"]["per_config"].items() if c != "no enhancer"}
    NUM["kscale"] = dict(drop_pp=[100 * min(drops.values()), 100 * max(drops.values())],
                         noenh=[ks["syn"]["per_config"]["no enhancer"]["erased_k1"], ks["syn"]["per_config"]["no enhancer"]["erased_k"]],
                         rho_syn=ks["syn"]["rho_meanR"], rho_acq=ks["acq"]["rho_meanR"])


def tab_selection():
    st = J("coauthor_stats_T2.json")
    ks = J("coauthor_kscale_T2.json")
    t7, t8, t9 = st["task7"], st["task8"], st["task9"]
    L = ["% Generated by figures/make_tabs_coauthor.py from out_public/coauthor_stats_T2.json and coauthor_kscale_T2.json.",
         r"\begin{table}[!htbp]", r"\floatconts{tab:selection}",
         r"{\caption{\textbf{The selection gap under four checks, through $D$ (unit 1).} Extra erasure (percentage points, "
         r"$\mathcal{R}<0.25$, per-seed estimand) of the SynthSeg-Dice pick over the retention leader on matched lesions. "
         r"As published: the picks of \figureref{fig:select}, with a subject-bootstrap interval (exploratory: 5 subjects "
         r"give 126 distinct resamples). Cross-fitted: both picks chosen on all subjects but one and scored on it "
         r"(mean over folds, with the number of folds with a positive gap). Without corpus: Dice picks again after the three corpus-pretrained "
         r"configurations are removed. $k$-scaled: as published, with $D$'s lesion response scaled by $k$.}}",
         r"{\scriptsize\setlength{\tabcolsep}{2.5pt}\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}llccccc@{}}",
         r"\toprule",
         r"Cohort & Arm & As published & Cross-fitted & Without corpus & Pick without corpus & $k$-scaled \\",
         r"\midrule"]
    NUM["selection"] = {}
    for sp in ("test", "ext_on_hfe", "ext_v5"):
        for arm in ("syn", "acq"):
            a, c = t7[sp]["HFC"][arm]["asis"], t7[sp]["HFC"][arm]["crossfit"]
            b = t9[sp]["HFC"][arm]["dE_perseed"]
            lf = t8[sp]["HFC"][arm]["leave_family_out"]
            k = ks[sp]["HFC"][arm]["delta"] if sp in ks else None
            L.append(f"{COHORT[sp] if arm == 'syn' else ''} & {'synthetic' if arm == 'syn' else 'acquired'} & "
                     f"{pp(a['dE_perseed'])} [{pp(b['lo'])}, {pp(b['hi'])}] & {pp(c['dE_perseed'])} ({c['n_positive_perseed']}/{c['n_folds']}) & "
                     f"{pp(lf['dE_perseed'])} & {NAME[lf['pick']]} & {pp(k['dE_perseed']) if k else '--'} \\\\")
            NUM["selection"][f"{sp}|{arm}"] = dict(asis=a["dE_perseed"], asis_seedmean=a["dE_seedmean"], dR=a["dR"],
                                                   ci=[b["lo"], b["hi"]], crossfit=c["dE_perseed"],
                                                   crossfit_pos=[c["n_positive_perseed"], c["n_folds"]],
                                                   lfo=lf["dE_perseed"], lfo_pick=lf["pick"],
                                                   kscaled=k["dE_perseed"] if k else None,
                                                   kscaled_seedmean=k["dE_seedmean"] if k else None)
    L += [r"\bottomrule", r"\end{tabular*}}", r"\end{table}"]
    write("tab_selection_rev.tex", "\n".join(L) + "\n")
    pos = sum(t7[sp][op]["acq"]["crossfit"][f"n_positive_{e}"] for sp in t7 for op in t7[sp] for e in ("seedmean", "perseed"))
    tot = sum(2 * t7[sp][op]["acq"]["crossfit"]["n_folds"] for sp in t7 for op in t7[sp])
    NUM["selection_acq_positive"] = [pos, tot]
    NUM["expectations"] = {k: v["pass"] for k, v in st["expectations"].items()}


def tab_mapbase():
    r = J("coauthor_baseline_T2.json")
    a, w = r["auroc"], r["within_radius"]
    L = ["% Generated by figures/make_tabs_coauthor.py from out_public/coauthor_baseline_T2.json.",
         r"\begin{table}[!htbp]", r"\floatconts{tab:mapbase}",
         r"{\caption{\textbf{Retention map against handcrafted baselines.} AUROC for erasure of the 1605 internal-test "
         r"lesions by the absolute-output U-Net, overall and within each lesion size. Handcrafted features of the "
         r"lesion-free 3T image at the site: radius, contrast, SynthSeg tissue class, distance to CSF, core and ring "
         r"intensity, local standard deviation and gradient magnitude, fitted on the map's 5754 training labels.}}",
         r"{\scriptsize\setlength{\tabcolsep}{3pt}\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lccccc@{}}",
         r"\toprule", r"Score & All & 4\,mm & 6\,mm & 8\,mm & 12\,mm \\", r"\midrule"]
    for k, nm in (("map", "Retention map (mean of four seeds)"), ("boosting", "Handcrafted, gradient boosting"),
                  ("logistic", "Handcrafted, logistic regression"), ("radius", "Lesion radius")):
        L.append(f"{nm} & {a[k]:.3f} & " + " & ".join(f"{w[k][s]:.3f}" for s in ("4", "6", "8", "12")) + r" \\")
    L += [r"\bottomrule", r"\end{tabular*}}", r"\end{table}"]
    write("tab_mapbase_rev.tex", "\n".join(L) + "\n")
    d = r["map_minus_best"]
    NUM["mapbase"] = dict(auroc=a, within=w, diff=[d["point"], d["lo"], d["hi"]], diff_pos=[d["n_positive"], d["n_subjects"]])


def numbers():
    dn = J("coauthor_denominator_T2.json")["sites"]
    per = {}
    for s in dn:
        per.setdefault(s["sid"], []).append(s["retention"] < 0.25)
    NUM["denominator"] = dict(n=len(dn), dropped=sum(not s["keep"] for s in dn),
                              per_subject=[100 * float(np.mean(v)) for v in per.values()])
    db = J("coauthor_darkbright_T2.json")["analysis"]
    NUM["darkbright"] = dict(paired=db["paired"], tertiles={k: [v["erased_dark"], v["erased_bright"], v["n"]]
                                                            for k, v in db["by_ring_tertile"].items()},
                             clipped=db["dark_core_clipped"], p=db["mcnemar_p"])
    if os.path.exists(f"{OUT}/coauthor_inpaint_T2.json"):
        ip = J("coauthor_inpaint_T2.json")
        NUM["inpaint"] = {k: ip[k] for k in ("rho_median", "rho_range", "erased_pick_median", "erased_pick_range", "n_lesions", "n_draws")}
        NUM["inpaint"]["E11a"] = ip["E11a"]["pass"]


if __name__ == "__main__":
    tab_seeds(); tab_selection(); tab_mapbase(); numbers()
    json.dump(NUM, open(f"{HERE}/coauthor_numbers.json", "w"), indent=1, default=float)
    print(json.dumps(NUM, indent=1, default=float)[:3000])
